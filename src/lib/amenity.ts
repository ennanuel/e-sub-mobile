export const ALL_AMENITIES_STORES = [
  ...AMENITIES_STORE,
  ...OTHER_AMENITIES_STORE,
];

export const findAmenityByName = (searchName: string) => {
  if (!searchName) return undefined;

  return (
    ALL_AMENITIES_STORES.find(
      (item) =>
        item.name.trim().toLowerCase() === searchName.trim().toLowerCase()
    )?.icon ?? ""
  );
};

